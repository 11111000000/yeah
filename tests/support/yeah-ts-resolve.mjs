/**
 * Резолвер импортов TypeScript без установленных зависимостей.
 *
 * Node умеет исполнять TypeScript сам (снятие типов), но требует в импорте
 * расширения файла: `./yeah` он не находит, а `./yeah.ts` — находит.  Плагин
 * написан в обычном стиле (`./yeah`), и менять его стиль ради проверки не
 * нужно: резолвер проверки дописывает расширение сам.
 *
 * Модуль ничего не знает про плагин: он правит только относительные импорты
 * без расширения и только те, рядом с которыми лежит файл `.ts`.
 */
import { register } from "node:module";

register("./yeah-ts-hooks.mjs", import.meta.url);
